// 20. Базовый while
// Цель: Проверка перед телом, счётчик и аккумулятор.
// В графе: Истинное ребро входит в тело, обратное возвращается к проверке; значения i и total сливаются.
int SumWhile(int n)
{
    int i = 0;
    int total = 0;
    while (i < n)
    {
        total = total + i;
        i = i + 1;
    }
    return total;
}
