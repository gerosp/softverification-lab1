// 24. Включительная граница цикла
// Цель: При n = 0 выполняется ровно одна итерация из-за <=.
// В графе: Проверить отличие < и <=: одна итерация при нулевой границе, ноль при отрицательной.
int InclusiveBound(int n)
{
    int count = 0;
    for (int i = 0; i <= n; i++)
    {
        count++;
    }
    return count;
}
