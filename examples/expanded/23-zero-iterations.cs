// 23. Ноль итераций
// Цель: Начальное значение сохраняется, когда тело недостижимо при данном входе.
// В графе: Путь от первой ложной проверки сразу ведёт за цикл; начальное определение достигает return.
int PreserveOnEmptyLoop(int n)
{
    int result = 7;
    for (int i = 0; i < n; i++)
    {
        result = result + 1;
    }
    return result;
}
