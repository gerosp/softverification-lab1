// 26. If внутри одного цикла
// Цель: Условное обновление аккумулятора без ранних переходов.
// В графе: Обе ветви if сходятся перед шагом for; для total есть слияние после if и на входе цикла.
int SumEven(int n)
{
    int total = 0;
    for (int i = 0; i < n; i++)
    {
        if (i % 2 == 0)
        {
            total = total + i;
        }
    }
    return total;
}
