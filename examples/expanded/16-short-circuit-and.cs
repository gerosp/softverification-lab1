// 16. Короткое замыкание &&
// Цель: Правая часть && вычисляется только при истинной левой.
// В графе: При divisor = 0 деление недостижимо; учесть отдельный путь короткого замыкания.
int GuardedDivisionAnd(int divisor)
{
    if (divisor != 0 && 100 / divisor > 4)
    {
        return 1;
    }
    return 0;
}
