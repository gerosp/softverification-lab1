// Цель: Три выхода из метода без общей переменной результата.
// В графе: Сравнить с 11: одинаковые результаты, другая структура CFG, нет слияния result.
int SignWithReturns(int x)
{
    if (x < 0)
    {
        return -1;
    }
    else if (x == 0)
    {
        return 0;
    }
    else
    {
        return 1;
    }
}
